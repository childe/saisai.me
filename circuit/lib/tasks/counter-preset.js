// 第 38 关「按钮计数器」的预置电路（布局由脚本排好后写死在这里）。
//
// 电路分三部分，全部是继电器：
// - 「现1/现2/现4/现8」：记住显示器上现在的数（二进制 4 位）。同一位的几个继电器线圈串在一起，一起吸合、一起释放，
//   只是触点多几组。每位第一个继电器的触点从正极接回自己的线圈（自锁），也接到显示器。
// - 「下1/下2/下4/下8」：记住下一个数。松开按钮时，「现」的触点组成的开关网络算出「现在的数 + 1」（9 之后是 0），送进「下」的线圈；
//   按下按钮时，「下」靠自己的触点自锁，不再变。
// - 「按」：跟着按钮动的 8 个继电器（上下两排各 4 个线圈串联）。每个「按」的触点是一个二选一：
//   松开时「现」自锁、「下」跟着算出来的数；按下时「现」改接「下」，「下」自锁。所以按一下只加 1，按住不放也不会一直加。
//
// 上排继电器转 90°（线圈朝上），下排转 270°（线圈朝下），触点都朝中间，触点之间的导线全走中间这条通道；
// 线圈之间的串联线和地线走上下两边。电池 4 节，最长的一串线圈（6 个）也有 30 mA 以上，够吸合。

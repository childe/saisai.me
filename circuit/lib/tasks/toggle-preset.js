// 继电器全部转 90°（线圈朝上、触点朝下），排列和计数器的最低位一样：按（现）、现、按（下）、下。
// 小朋友要补的两根线都在触点下面的通道里：现.no → 按（现）.nc（自锁），现.nc → 按（下）.nc（下一个数 = 现在反过来）。
